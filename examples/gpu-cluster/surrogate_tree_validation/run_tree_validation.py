#!/usr/bin/env python3
"""Re-run the paper exp3 tree ground truth on the FIXED protobridge ns-3.

The paper's 653-row tree ground truth (doc/paper/experiments/exp3_surrogate/
parsed/results.csv, June 2026) was generated by the PARENT repo's ns-3 binary
whose TreeAllReduce under-transferred data (fixed in protobridge de16a7c
2026-09-16: chunk-pipelined rewrite carrying the full D per tree edge).
The 2026-09-18 surrogate tree recalibration (f984edb) was fitted against the
FIXED simulator. This script re-runs a stratified sample of the paper's exact
tree commands on the protobridge binary and evaluates BOTH surrogate tree
models (the paper fork's old BW_link*eta_sw*log2N formula and the
recalibrated alpha(N) trunk-load model) against the corrected ground truth.

Reads only from the parent repo (command list, paper fork surrogate);
writes only inside protobridge (this directory).
"""
import csv
import os
import re
import subprocess
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed

HERE = os.path.dirname(os.path.abspath(__file__))
PB_BIN = "/share_data/zhuyu/ns-3.47/protobridge/build/scratch/ns3.47-gpu-cluster-sim-debug"
RUNS = os.path.join(HERE, "tree_runs.txt")
OUT = os.path.join(HERE, "results_tree_rerun.csv")

PAT = re.compile(r'e3_n(\d+)_tre_s(\d+)_ber([\d.e-]+)_fec(\d+)_llr(\d+)_cr(\d+)_r(\d+)')
TIMEOUT = 3600


def run_one(line):
    key, cmd = line.split("\t", 1)
    n, sz, ber, fec, llr, cr = key.split(",")
    try:
        r = subprocess.run(cmd.split(), capture_output=True, text=True,
                           timeout=TIMEOUT, cwd="/share_data/zhuyu/ns-3.47/protobridge")
        text = r.stdout + r.stderr
    except subprocess.TimeoutExpired:
        return key, None, "timeout"
    m = re.search(r'simTimeUs=([\d.]+)', text)
    s = re.search(r'status=(\w+)', text)
    return key, (float(m.group(1)) if m else None), (s.group(1) if s else "no_result")


def main():
    lines = [l.strip() for l in open(RUNS) if l.strip()]
    rows = []
    with ProcessPoolExecutor(max_workers=16) as ex:
        futs = {ex.submit(run_one, l): l for l in lines}
        done = 0
        for fut in as_completed(futs):
            key, us, status = fut.result()
            n, sz, ber, fec, llr, cr = key.split(",")
            rows.append(dict(num_gpus=int(n), data_size=int(sz), ber=float(ber),
                             fec=int(fec), llr=int(llr), cr=int(cr),
                             sim_us=us, status=status))
            done += 1
            if done % 30 == 0:
                print(f"{done}/{len(lines)}", flush=True)
    with open(OUT, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["num_gpus", "data_size", "ber", "fec",
                                          "llr", "cr", "sim_us", "status"])
        w.writeheader()
        w.writerows(rows)
    ok = sum(1 for r in rows if r["status"] == "complete" and r["sim_us"])
    print(f"wrote {OUT}: {ok}/{len(rows)} complete")


if __name__ == "__main__":
    main()
